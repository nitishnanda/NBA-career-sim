"""Draft combine data for the game (src/combine.js, loaded after sizes.js).
Source: the Kaggle NBA draft combine file (2000-2026, 1,748 prospects; barefoot height, weight, wingspan, standing reach, standing and max vertical, lane agility, 3/4-court
sprint, shuttle, bench-press reps) and the Basketball-Reference files. Writes, per position (PG SG SF PF C; a combined position counts as its first):
  - mean, sd and percentiles of every measurement (the tables a prospect is ranked against),
  - how the tests relate (loadings on a common athleticism factor, effects of size on the tests: heavier / taller prospects test a little slower),
  - standing reach from height and wingspan, and
  - a pool of real players with 4+ NBA seasons for 'measurables comps'.
Usage: python3 -I scripts/real-combine.py path/to/'Draft Combine - Kaggle.csv' [path/to/bball-reference-datasets/Data]"""
import json, os, sys, unicodedata
import numpy as np, pandas as pd
SRC = sys.argv[1]; D = sys.argv[2] if len(sys.argv) > 2 else '/home/user/sumitrodatta/bball-reference-datasets/Data/'
c = pd.read_csv(SRC, na_values=['NA'])
for k in ['WGT', 'SHUTTLE', 'LANE', 'SPRINT', 'STNDVERT', 'LPVERT', 'BENCH']: c.loc[c[k] <= 0, k] = np.nan
c['p1'] = c.POS.str.split('-').str[0]; c = c[c.p1.isin(['PG', 'SG', 'SF', 'PF', 'C'])]
TESTS = {'hgt': 'HGT', 'wgt': 'WGT', 'ws': 'WNGSPN', 'reach': 'STNDRCH', 'stv': 'STNDVERT', 'mxv': 'LPVERT', 'lane': 'LANE', 'sprint': 'SPRINT', 'shuttle': 'SHUTTLE', 'bench': 'BENCH'}
PCT = [5, 10, 25, 50, 75, 90, 95]
tab = {}
for p in ['PG', 'SG', 'SF', 'PF', 'C']:
    x = c[c.p1 == p]; tab[p] = {k: dict(n=int(x[v].notna().sum()), m=round(float(x[v].mean()), 3), sd=round(float(x[v].std()), 3), p=[round(float(x[v].quantile(q / 100)), 2) for q in PCT]) for k, v in TESTS.items()}
# within-position z-scores (timed tests flipped so + is better)
z = c[['YEAR', 'PLAYER', 'p1']].copy()
for k, v in TESTS.items(): z[k] = (c[v] - c.groupby('p1')[v].transform('mean')) / c.groupby('p1')[v].transform('std')
for k in ['lane', 'sprint', 'shuttle']: z[k] = -z[k]
z['vert'] = z[['stv', 'mxv']].mean(axis=1)
C = z[['hgt', 'wgt', 'ws', 'vert', 'lane', 'sprint', 'shuttle']].corr()
# one-factor loadings of vertical, sprint, lane from their three correlations; shuttle follows lane
lv = float(np.sqrt(C.loc['vert', 'sprint'] * C.loc['vert', 'lane'] / C.loc['sprint', 'lane'])); ls = C.loc['vert', 'sprint'] / lv; ll = C.loc['vert', 'lane'] / lv
load = dict(vert=round(lv, 3), sprint=round(float(ls), 3), lane=round(float(ll), 3), shuttle=round(float(ll), 3))
# effect of size on the tests (z of the test per +1 sd of height / weight, both entered)
eff = {}
for k in ['vert', 'lane', 'sprint', 'shuttle']:
    y = z[[k, 'hgt', 'wgt']].dropna(); b = np.linalg.lstsq(np.c_[np.ones(len(y)), y.hgt, y.wgt], y[k], rcond=None)[0]; eff[k] = dict(hgt=round(float(b[1]), 3), wgt=round(float(b[2]), 3))
r = c.dropna(subset=['HGT', 'WNGSPN', 'STNDRCH']); b = np.linalg.lstsq(np.c_[np.ones(len(r)), r.HGT, r.WNGSPN], r.STNDRCH, rcond=None)[0]; res = r.STNDRCH - np.c_[np.ones(len(r)), r.HGT, r.WNGSPN] @ b
reach = dict(a=round(float(b[0]), 3), h=round(float(b[1]), 3), w=round(float(b[2]), 3), sd=round(float(res.std()), 2))
# comps: combine prospects who played 4+ NBA seasons (20+ games)
norm = lambda s: ''.join(ch for ch in unicodedata.normalize('NFKD', s) if not unicodedata.combining(ch)).lower().replace('.', '').replace("'", '').replace('-', ' ').replace(',', '').strip()
def key(n, flipped):
    if flipped:
        a = n.split(', '); n = (a[1] + ' ' + a[0]) if len(a) == 2 else n
    n = norm(n)
    for s in [' jr', ' sr', ' iii', ' ii']: n = n.replace(s, '')
    return n.strip()
pg = pd.read_csv(D + 'Player Per Game.csv'); pg = pg[(pg.lg == 'NBA') & (pg.g >= 20)].drop_duplicates(['player_id', 'season'])
ns = pg.groupby('player_id').season.nunique(); nm = pg.drop_duplicates('player_id').set_index('player_id').player
pro = pd.DataFrame({'player': nm, 'seasons': ns}); pro = pro[pro.seasons >= 4]; pro['k'] = pro.player.map(lambda s: key(s, False)); pro = pro.drop_duplicates('k')
c['k'] = c.PLAYER.map(lambda s: key(s, True)); cc = c.dropna(subset=['HGT', 'WNGSPN', 'WGT']).merge(pro[['k', 'player', 'seasons']], on='k')
cc = cc[cc.YEAR <= 2022]
comps = [[r.player, r.p1, round(r.HGT, 2), int(r.WGT), round(r.WNGSPN, 2), (round(float(r.LPVERT), 1) if pd.notna(r.LPVERT) else None), (round(float(r.SPRINT), 2) if pd.notna(r.SPRINT) else None), (round(float(r.LANE), 2) if pd.notna(r.LANE) else None), int(r.YEAR)] for r in cc.itertuples()]
out = dict(tab=tab, load=load, eff=eff, reach=reach, comps=comps, n=int(len(c)))
json.dump(out, open(os.path.join(os.path.dirname(__file__), '..', 'data', 'real-combine.json'), 'w'), separators=(',', ':'))
js = "(function (g) {\n  // GENERATED by scripts/real-combine.py from the Kaggle NBA draft combine file (2000-2026): per-position tables, test structure, comps pool\n  const NBA = (g.NBA = g.NBA || {});\n  NBA.COMBINE = " + json.dumps(out, separators=(',', ':'), ensure_ascii=False) + ";\n})(typeof window !== 'undefined' ? window : globalThis);\n"
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'combine.js'), 'w', encoding='utf8').write(js)
print('prospects', len(c), '| comps', len(comps), '| loadings', load, '| size effects', eff, '| reach', reach)
print({p: {k: (tab[p][k]['m'], tab[p][k]['sd']) for k in ['hgt', 'wgt', 'ws', 'mxv', 'sprint', 'lane']} for p in ['PG', 'C']})
