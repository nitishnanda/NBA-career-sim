"""Real heights and weights for the real-roster players (src/sizes.js, loaded after real.js).
Position distributions (D.SIZE in src/data.js) were measured on NBA players since 2005 with 40+ games at 18+ mpg, one row a player, listed position
= the position he mostly played (Basketball-Reference Player Career Info + Player Per Game, n 210-252 a position): mean height / sd / 2nd-98th
percentile, mean weight and the sd of weight at a given height (weight rises ~2.5 lb an inch within a position).
Usage: python3 -I scripts/real-sizes.py [path/to/bball-reference-datasets/Data]"""
import json, os, re, sys, unicodedata
import pandas as pd
D = sys.argv[1] if len(sys.argv) > 1 else '/home/user/sumitrodatta/bball-reference-datasets/Data/'
src = open(os.path.join(os.path.dirname(__file__), '..', 'src', 'real.js'), encoding='utf8').read()
names = re.findall(r'\["([^"]+)", "(?:PG|SG|SF|PF|C)", \d+, \d+', src)
ci = pd.read_csv(D + 'Player Career Info.csv').dropna(subset=['ht_in_in', 'wt'])
norm = lambda s: ''.join(c for c in unicodedata.normalize('NFKD', s) if not unicodedata.combining(c)).lower().replace('.', '').replace("'", '').replace('-', ' ').strip()
ci['k'] = ci.player.map(norm); m = ci.sort_values('to').drop_duplicates('k', keep='last').set_index('k')
BY_HAND = {'Egor Demin': (80, 195)}   # too new for the file (6'8", 195 lb)
out = {}
for n in names:
    if n in BY_HAND: out[n] = list(BY_HAND[n])
    elif norm(n) in m.index: out[n] = [int(m.loc[norm(n)].ht_in_in), int(m.loc[norm(n)].wt)]
missing = [n for n in names if n not in out]
assert not missing, missing
js = '(function (g) {\n  // GENERATED by scripts/real-sizes.py: [height in inches, weight in lb] of the real-roster players\n  const NBA = (g.NBA = g.NBA || {});\n  NBA.REAL_SIZES = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n})(typeof window !== \'undefined\' ? window : globalThis);\n'
open(os.path.join(os.path.dirname(__file__), '..', 'src', 'sizes.js'), 'w', encoding='utf8').write(js)
print('real sizes', len(out))
